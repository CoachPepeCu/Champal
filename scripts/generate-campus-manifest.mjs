import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const photosRoot = path.join(projectRoot, "public", "images", "Explora", "Campus");
const outputFile = path.join(projectRoot, "src", "data", "campusPhotos.generated.js");
const allowedExtensions = new Set([".webp", ".png", ".jpg", ".jpeg", ".avif"]);
const collator = new Intl.Collator("es", { numeric: true, sensitivity: "base" });

const labels = [
  "Salones",
  "Biblioteca",
  "Juegos",
  "Áreas verdes",
  "Espacios deportivos",
  "Laboratorio",
  "Servicio médico",
  "Cafeterías",
  "Aula Feel",
  "Wi‑Fi",
  "Seguridad",
  "Maker",
  "Cabina",
  "Artes",
  "Auditorio",
];

function publicPhotoPath(id, fileName) {
  return `/images/Explora/Campus/${id}/${encodeURIComponent(fileName)}`;
}

async function readArea(id, label) {
  const directory = path.join(photosRoot, id);
  let entries = [];

  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  const photos = entries
    .filter((entry) => entry.isFile() && allowedExtensions.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((left, right) => collator.compare(left, right))
    .map((fileName) => publicPhotoPath(id, fileName));

  return {
    id,
    label,
    icon: `/images/conoce-champal/campus/icon-${id}.webp`,
    photos,
  };
}

async function generateManifest() {
  const areas = await Promise.all(
    labels.map((label, index) => readArea(String(index + 1).padStart(2, "0"), label)),
  );
  const source = `// This file is generated by scripts/generate-campus-manifest.mjs.\n// Do not edit it by hand.\n\nexport const campusAreas = ${JSON.stringify(areas, null, 2)};\n`;

  await fs.mkdir(path.dirname(outputFile), { recursive: true });
  await fs.writeFile(outputFile, source, "utf8");
  process.stdout.write(`Campus manifest generated: ${path.relative(projectRoot, outputFile)}\n`);
}

generateManifest().catch((error) => {
  process.stderr.write(`Unable to generate the Campus manifest: ${error.message}\n`);
  process.exitCode = 1;
});
